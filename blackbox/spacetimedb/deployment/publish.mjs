import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../../..');
const target=process.argv[2];
if(!['local','maincloud'].includes(target))throw Error('Usage: node deployment/publish.mjs local|maincloud [--env-only]');
const cli=resolve(process.env.LOCALAPPDATA,'SpacetimeDB/bin/current/spacetimedb-cli.exe');
const config=target==='local'?resolve(process.env.LOCALAPPDATA,'SpacetimeDB/config/cli.toml'):resolve(root,'blackbox/spacetimedb/.env.maincloud-cli.toml');
const secrets=JSON.parse(readFileSync(resolve(root,'blackbox/spacetimedb/.env.anchor.production.json'),'utf8'));
const database=target==='local'?'blackbox':'blackbox-utd2026-abbas9x';
const server=target==='local'?'http://127.0.0.1:3000':'maincloud';
const args=['--config-path',config,'publish',database,'--server',server,'--module-path',resolve(root,'blackbox/spacetimedb'),'--no-config','--yes','--delete-data=never'];
if(process.argv.includes('--env-only'))args.push('--env-only');
const result=spawnSync(cli,args,{cwd:root,env:{...process.env,...secrets},encoding:'utf8',windowsHide:true});
process.stdout.write(result.stdout??'');process.stderr.write(result.stderr??'');process.exit(result.status??1);
